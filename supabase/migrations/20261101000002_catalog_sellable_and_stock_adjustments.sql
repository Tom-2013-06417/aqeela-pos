-- Epic 3: internal (non-sale) products + damage/loss stock adjustments.

alter table public.products
  add column if not exists sellable boolean not null default true;

comment on column public.products.sellable is
  'When false, product is for business use only and hidden from the cashier catalog.';

create table public.stock_adjustments (
  id bigint generated by default as identity primary key,
  product_id uuid not null references public.products (id) on delete cascade,
  store_id uuid not null references public.stores (id) on delete cascade,
  qty_delta numeric(12, 3) not null,
  reason text not null check (reason in ('damage', 'loss', 'correction')),
  note text,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);

create index stock_adjustments_store_id_idx on public.stock_adjustments (store_id);
create index stock_adjustments_product_id_idx on public.stock_adjustments (product_id);
create index stock_adjustments_created_at_idx on public.stock_adjustments (created_at desc);

grant select, insert, update, delete on public.stock_adjustments to authenticated, service_role;
grant select on public.stock_adjustments to powersync_role;

do $$
declare
  seq_name text;
begin
  seq_name := pg_get_serial_sequence('public.stock_adjustments', 'id');
  if seq_name is not null then
    execute format('grant usage, select on sequence %s to authenticated, service_role', seq_name);
  end if;
end $$;

alter table public.stock_adjustments enable row level security;

create policy "staff read store stock adjustments"
  on public.stock_adjustments for select to authenticated
  using (
    store_id in (select store_id from public.store_staff where user_id = auth.uid())
  );

create policy "staff insert store stock adjustments"
  on public.stock_adjustments for insert to authenticated
  with check (
    store_id in (select store_id from public.store_staff where user_id = auth.uid())
  );

-- Adjustments are append-only from the app; no update/delete policies for authenticated.

alter publication powersync add table public.stock_adjustments;
