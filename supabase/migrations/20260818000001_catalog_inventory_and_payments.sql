drop trigger if exists stores_seed_rice_category on public.stores;
drop function if exists public.seed_rice_category_for_store();

-- Collapse duplicate Rice presets onto the oldest row.
do $$
declare
  keep_id uuid;
begin
  select id into keep_id
  from public.categories
  where slug = 'rice'
  order by created_at, id
  limit 1;

  if keep_id is not null then
    update public.products
    set category_id = keep_id
    where category_id in (select id from public.categories where slug = 'rice')
      and category_id is distinct from keep_id;

    delete from public.categories
    where slug = 'rice'
      and id is distinct from keep_id;
  end if;
end $$;

drop policy "staff read store categories" on public.categories;
drop policy "staff insert store categories" on public.categories;
drop policy "staff update store categories" on public.categories;
drop policy "staff delete store categories" on public.categories;

alter table public.categories drop constraint if exists categories_store_id_slug_key;
drop index if exists public.categories_store_id_idx;

alter table public.categories drop column store_id;

alter table public.categories
  add constraint categories_slug_key unique (slug);

insert into public.categories (name, slug)
select 'Rice', 'rice'
where not exists (select 1 from public.categories where slug = 'rice');

create policy "staff read catalog categories"
  on public.categories for select to authenticated
  using (
    exists (select 1 from public.store_staff where user_id = auth.uid())
  );

create policy "staff insert catalog categories"
  on public.categories for insert to authenticated
  with check (
    exists (select 1 from public.store_staff where user_id = auth.uid())
  );

create policy "staff update catalog categories"
  on public.categories for update to authenticated
  using (
    exists (select 1 from public.store_staff where user_id = auth.uid())
  )
  with check (
    exists (select 1 from public.store_staff where user_id = auth.uid())
  );

create policy "staff delete catalog categories"
  on public.categories for delete to authenticated
  using (
    exists (select 1 from public.store_staff where user_id = auth.uid())
      and (slug is distinct from 'rice')
  );

